export const supportedAppLanguages = ["en", "zh-CN"] as const satisfies readonly AppLanguage[];

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "zh-CN";
}

export function resolveSystemAppLanguage(locale: string | undefined): AppLanguage {
  if (!locale) {
    return "en";
  }
  try {
    const parsed = new Intl.Locale(locale).maximize();
    return parsed.language === "zh" && parsed.script === "Hans" ? "zh-CN" : "en";
  } catch {
    return /^zh(?:[-_](?:CN|SG|MY|Hans))?/i.test(locale) ? "zh-CN" : "en";
  }
}

